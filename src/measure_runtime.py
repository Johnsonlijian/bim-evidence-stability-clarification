"""Computational cost: diagnosis time per model (full level, US rulebook) and planner time per request.

Usage: python -E -P measure_runtime.py <R10 dir> "<processor description>"
Writes outputs/results/runtime.json and manuscript/numbers_runtime.tex.
"""
import json
import math
import re
import statistics
import sys
import time
from pathlib import Path

R10 = Path(sys.argv[1])
CPU = sys.argv[2] if len(sys.argv) > 2 else "unspecified processor"
sys.path.insert(0, str(R10 / "src"))
from bimev.engine import build_clusters  # noqa: E402

rows = []
for sub in ("dev", "heldout"):
    for lf in sorted((R10 / "outputs" / sub / "ledgers").glob("ledger_*.json")):
        L = json.loads(lf.read_text(encoding="utf-8"))
        times = []
        for _ in range(3):
            t0 = time.perf_counter()
            cl = build_clusters(L, "full", "US")
            times.append(time.perf_counter() - t0)
        max_sh = max((math.prod(len(cm.domain(v)) for v in cm.shared) if cm.shared else 1) for cm in cl.values())
        max_h = max(len(h) for cm in cl.values() for h in cm.vs.values())
        rows.append({"project": L["project"], "set": sub, "groups": len(L["groups"]), "clusters": len(cl),
                     "checks": sum(g["multiplicity"] for g in L["groups"].values()),
                     "diag_s": statistics.median(times), "max_shared_assignments": max_sh, "max_hypotheses": max_h})
        print(rows[-1], flush=True)

# planner time from the Experiment 3 records (stability-based VOI, full level)
plan = {}
for sub in ("dev", "heldout"):
    fp = R10 / "outputs" / sub / "e2" / "e2_main.jsonl"
    if not fp.exists():
        continue
    with open(fp, encoding="utf-8") as fh:
        for line in fh:
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            if r["policy"] == "sv" and r["level"] == "full":
                n_req = (r.get("n_clarify") or 0) + (r.get("n_value") or 0)
                plan.setdefault(r["project"], []).append((r.get("secs") or 0.0, n_req))
per_req = [s / n for v in plan.values() for s, n in v if n > 0]
run_s = {p: statistics.median(s for s, _ in v) for p, v in plan.items()}
out = {"cpu": CPU, "models": rows, "planner_run_median_s": run_s,
       "planner_per_request_median_s": statistics.median(per_req) if per_req else None}
(R10 / "outputs" / "results" / "runtime.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
held = [r for r in rows if r["set"] == "heldout"]
mx = max(held, key=lambda r: r["diag_s"])
NAMES = {"city_house_munich": "City house Munich", "duplex": "Duplex apartment",
         "fantasy_office_building_1": "Student office 1", "wbdg_office": "WBDG office",
         "fantasy_hotel_1": "Student hotel 1", "fantasy_hotel_2": "Student hotel 2",
         "fantasy_office_building_2": "Student office 2", "fantasy_office_building_3": "Student office 3",
         "fantasy_residential_building_1": "Student residential 1", "hitos": "HITOS", "molio": "Molio demo building",
         "sixty5": "Sixty5", "west_riverside_hospital": "West Riverside hospital"}
held_runs = {p: v for p, v in run_s.items() if p in {r["project"] for r in held}}
# ledger extraction time per held-out model (declared catalogue), from the extraction logs (parallel extraction)
ext = {}
for lf in (R10 / "outputs" / "extract_logs").glob("heldout_*_ledgers.log"):
    txt = lf.read_text(encoding="utf-8", errors="ignore").strip().splitlines()
    m = re.search(r"([0-9.]+)s\s*$", txt[-1]) if txt else None
    if m:
        ext[lf.name[len("heldout_"):-len("_ledgers.log")]] = float(m.group(1))
out["extraction_s"] = ext
(R10 / "outputs" / "results" / "runtime.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
M = {
    "RtCpu": CPU,
    "RtDiagTotalHeldMs": f"{1000 * sum(r['diag_s'] for r in held):,.0f}",
    "RtDiagMaxHeldMs": f"{1000 * mx['diag_s']:,.0f}",
    "RtDiagMaxModel": NAMES.get(mx["project"], mx["project"]),
    "RtExtractMin": f"{min(ext.values()):.0f}" if ext else "--",
    "RtExtractMax": f"{max(ext.values()):.0f}" if ext else "--",
    "RtExtractMaxModel": NAMES.get(max(ext, key=ext.get), "--") if ext else "--",
    "RtMaxShared": f"{max(r['max_shared_assignments'] for r in rows):,}",
    "RtMaxHyp": f"{max(r['max_hypotheses'] for r in rows):,}",
    "RtPlanRunMax": f"{max(held_runs.values()):.1f}" if held_runs else "--",
    "RtPlanRunMaxModel": NAMES.get(max(held_runs, key=held_runs.get), "--") if held_runs else "--",
    "RtPerRequestMs": f"{1000 * out['planner_per_request_median_s']:.0f}" if per_req else "--",
}
with open(R10 / "manuscript" / "numbers_runtime.tex", "w", encoding="utf-8") as fh:
    fh.write("% Generated by measure_runtime.py -- do not edit by hand\n")
    for k, v in M.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(M)
